import JSZip from 'jszip';
import type { Evaluation, Invention, Project } from './types.js';

function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
}

/** Markdown design specification for one invention. */
export function designSpec(project: Project, inv: Invention): string {
  const sources = project.discoveries.filter((d) => inv.sourceIds.includes(d.id));

  return [
    `# ${inv.title}`,
    '',
    `> Generated by Daisy Invention Engine for **${project.query}**`,
    '',
    '## Summary',
    inv.summary,
    '',
    '## Hypothesis',
    inv.hypothesis,
    '',
    '## Components',
    ...inv.componentNames.map((n) => `- ${n}`),
    '',
    `Fields: ${inv.fields.join(', ')}`,
    '',
    '## Mechanism',
    ...inv.mechanism.map((m, i) => `${i + 1}. ${m}`),
    '',
    '## Risks',
    ...inv.risks.map((r) => `- ${r}`),
    '',
    '## Evidence status',
    '**Hypothesis only — no measured performance result is available.** Source links are research leads, not proof that this design works.',
    '',
    '- Expected gain: not established',
    '- Uncertainty: not established',
    `- Complexity descriptor: ${inv.complexity}/5 (design heuristic, not measured performance)`,
    '- Experimental validation: pending independent, controlled measurement.',
    '',
    '## Source provenance',
    ...sources.map((s) => `- [${s.title}](${s.url}) — metadata: ${s.sourceVerification || 'unverified'} (${s.sourceVerificationDetail || 'not checked'}); scientific claims are not independently verified.`),
    '',
    '## Evidence',
    'No abstract-derived statement is treated as independently verified evidence.',
    '',
  ].join('\n');
}

/** Runnable TypeScript prototype model of the invention. */
function prototypeModule(inv: Invention): string {
  return `/**
 * Design scaffold only: ${inv.title}
 * Components: ${inv.componentNames.join(', ')}
 *
 * This file intentionally contains no synthetic performance model.
 * Implement and validate a physical/software prototype, define a baseline,
 * collect raw measurements, and document the protocol before calculating results.
 */
export const design = {
  title: ${JSON.stringify(inv.title)},
  components: ${JSON.stringify(inv.componentNames)},
  complexityDescriptor: ${inv.complexity},
  measuredPerformance: 'NOT_ESTABLISHED',
  validationStatus: 'HYPOTHESIS_ONLY',
} as const;
`;
}

/**
 * Build the Export integration package (zip): README, per-invention design specs,
 * design scaffolds, evaluation report and raw research data.
 * @param project - the project
 * @param evaluation - Evaluate output
 * @param inventionIds - optional subset to include
 */
export async function buildExportPackage(project: Project, evaluation: Evaluation, inventionIds?: string[]): Promise<Buffer> {
  const zip = new JSZip();
  const root = zip.folder(`daisy-${slug(project.query)}`)!;
  const inventions = project.inventions.filter((i) => !inventionIds?.length || inventionIds.includes(i.id));

  root.file(
    'README.md',
    [
      `# Daisy Invention Package — ${project.query}`,
      '',
      `Generated ${new Date().toISOString()} from ${project.discoveries.length} sources, ${project.components.length} technical components and ${project.connections.length} connections.`,
      '',
      `Adjacent domains explored: ${project.domains.join(', ') || 'none'}`,
      '',
      '## Contents',
      '- `inventions/<name>/DESIGN.md` — design specification, mechanism, risks, evidence',
      '- `inventions/<name>/prototype.ts` — design scaffold; no simulated performance claims',
      '- `inventions/<name>/invention.json` — machine-readable design',
      '- `EVALUATION.md` — evidence status; no measured comparison is available',
      '- `data/` — raw discoveries, components and connections',
      '',
      '## Integration',
      '```ts',
      "import { design } from './inventions/<name>/prototype';",
      'console.log(design.validationStatus);',
      '```',
      '',
      '## Evidence status — numeric ranking disabled until measured evidence exists',
      ...evaluation.rows.map((r) => `- ${r.title} — ${r.evidenceStatus}; numeric ranking not established`),
      '',
    ].join('\n'),
  );

  root.file(
    'EVALUATION.md',
    [
      '# Evaluation',
      '',
      `Numeric scoring disabled until measured evidence exists.`,
      '',
      '| Design | Feasibility | Impact | Evidence | Risk | Overall | Validation |',
      '|---|---|---|---|---|---|---|',
      ...evaluation.rows.map(
        (r) => `| ${r.title} | ${r.feasibility ?? 'not established'} | ${r.impact ?? 'not established'} | ${r.evidence ?? 'not established'} | ${r.risk ?? 'not established'} | **${r.overall ?? 'not established'}** | ${r.evidenceStatus} |`,
      ),
      '',
      '## Measurement evidence — ingestion is not verification',
      ...((project.evidenceMeasurements || []).map((m) => `- ${m.title} — ${m.status}; protocol ${m.protocol.id} v${m.protocol.version}; n=${m.sampleSize}; dataset SHA-256 ${m.dataset.sha256}; analysis SHA-256 ${m.analysis.codeSha256}`)),
      '',
      'No measurement record is promoted to independently verified. Operator-supplied metadata and remote hashes are recorded but not independently authenticated or re-computed by this service.',
      '',
      '## Claim-level evidence provenance — exact abstract quotes, not verified findings',
      ...((project.evidenceClaims || []).map((c) => `- [${c.sourceTitle}](${c.sourceUrl}) sentence ${c.locator.sentenceIndex + 1}: ${c.text} — ${c.reviewStatus}; ${c.evidenceGrade}; semantic support and independent corroboration not established`)),
      '',
      '## Literature leads — extracted claims are unverified',
      ...evaluation.benchmarks.map((b) => `- "${b.claim}" — [${b.source}](${b.url})`),
      '',
    ].join('\n'),
  );

  const invFolder = root.folder('inventions')!;
  for (const inv of inventions) {
    const f = invFolder.folder(slug(inv.title))!;
    f.file('DESIGN.md', designSpec(project, inv));
    f.file('prototype.ts', prototypeModule(inv));
    f.file('invention.json', JSON.stringify(inv, null, 2));
  }

  const data = root.folder('data')!;
  data.file('discoveries.json', JSON.stringify(project.discoveries, null, 2));
  data.file('evidence-claims.json', JSON.stringify(project.evidenceClaims || [], null, 2));
  data.file('measurement-evidence.json', JSON.stringify(project.evidenceMeasurements || [], null, 2));
  data.file('components.json', JSON.stringify(project.components, null, 2));
  data.file('connections.json', JSON.stringify(project.connections, null, 2));

  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}
